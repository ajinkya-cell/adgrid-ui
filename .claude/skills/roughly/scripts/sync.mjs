#!/usr/bin/env node
/**
 * Maintainers: regenerate references/props.md from the Roughly component sources (their JSDoc).
 *
 *   node scripts/sync.mjs [path/to/roughly/dir]
 *
 * Default source: <repo>/packages/ui/src/animated/roughly (when run from the adgrid-ui repo).
 * Also works on an installed copy, e.g. `node sync.mjs src/components/ui/roughly/roughly`.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const skillDir = path.resolve(here, "..");
const src = path.resolve(process.argv[2] ?? path.resolve(skillDir, "../../../packages/ui/src/animated/roughly"));
if (!fs.existsSync(src)) {
  console.error(`Source folder not found: ${src}`);
  process.exit(1);
}

const COMPONENTS = [
  ["Roughly.Underline", "RoughUnderline"],
  ["Roughly.Circle", "RoughCircle"],
  ["Roughly.Highlight", "RoughHighlight"],
  ["Roughly.Box", "RoughBox"],
  ["Roughly.Bracket", "RoughBracket"],
  ["Roughly.Strike", "RoughStrike"],
  ["Roughly.Cross", "RoughCross"],
  ["Roughly.Check", "RoughCheck"],
  ["Roughly.Arrow", "RoughArrow"],
  ["Roughly.Sticky", "RoughSticky"],
  ["Roughly.Handwriting", "RoughHandwriting"],
];

function parseProps(file, name) {
  const text = fs.readFileSync(file, "utf8").replace(/\r\n/g, "\n");
  const start = text.indexOf(`export interface ${name}Props {`);
  if (start < 0) return null;
  const body = text.slice(start, text.indexOf("\n}", start));
  const lines = body.split("\n").slice(1);
  const props = [];
  let doc = [];
  let inDoc = false;
  for (const raw of lines) {
    const line = raw.trim();
    if (line.startsWith("/**")) {
      inDoc = !line.endsWith("*/");
      doc = [line.replace(/^\/\*\*\s?/, "").replace(/\s?\*\/$/, "")];
      continue;
    }
    if (inDoc) {
      if (line.endsWith("*/")) inDoc = false;
      const piece = line.replace(/\*\/$/, "").replace(/^\*\s?/, "").trim();
      if (piece) doc.push(piece);
      continue;
    }
    const m = line.match(/^(\w+)(\?)?:\s*(.+);$/);
    if (m) {
      const description = doc.join(" ").trim();
      props.push({
        name: m[1],
        optional: !!m[2],
        type: m[3],
        description,
        deprecated: /@deprecated/.test(description),
      });
      doc = [];
    }
  }
  return props;
}

function typeAliases(file) {
  const text = fs.readFileSync(file, "utf8");
  return [...text.matchAll(/export type (\w+) =\s*([^;]+);/g)].map((m) => [m[1], m[2].replace(/\s+/g, " ").trim()]);
}

const esc = (s) => s.replace(/\|/g, "\\|");
let out = `# Props reference

Generated by \`scripts/sync.mjs\` from the component sources. Don't edit by hand.
Use the namespaced components (\`Roughly.Circle\` …); they accept every prop below.
\`<Roughly type="…">\` only forwards a subset (and prefixes arrow props with \`arrow\`).

Deprecated props are listed last per component; don't use them.
`;

for (const [label, name] of COMPONENTS) {
  const file = path.join(src, `${name}.tsx`);
  if (!fs.existsSync(file)) {
    out += `\n## ${label}\n\n_Not found in this version._\n`;
    continue;
  }
  const props = parseProps(file, name) ?? [];
  const aliases = typeAliases(file);
  props.sort((a, b) => Number(a.deprecated) - Number(b.deprecated));
  out += `\n## ${label}\n\n`;
  if (aliases.length) {
    out += aliases.map(([n, t]) => `- \`${n}\` = \`${esc(t)}\``).join("\n") + "\n\n";
  }
  out += `| Prop | Type | Description |\n|---|---|---|\n`;
  for (const p of props) {
    const n = p.deprecated ? `~~${p.name}~~` : `\`${p.name}\`${p.optional ? "" : " (required)"}`;
    out += `| ${n} | \`${esc(p.type)}\` | ${esc(p.description)} |\n`;
  }
}

const dest = path.join(skillDir, "references", "props.md");
fs.writeFileSync(dest, out);
console.log(`wrote ${path.relative(process.cwd(), dest)} from ${src}`);
